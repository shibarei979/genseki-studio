-- ============================================================
-- 原石航路 Studio
-- 人物に「登場する章」を持たせる
--
-- ------------------------------------------------------------
-- 何のために足すか
--
-- 関係図を、章ごとに見られるようにする。
--
--   最初は敵 → 途中で協力 → 最後は仲間
--
-- 小説では、こういう変わり方をする。
-- いまの関係図は、全部の時点を一枚に重ねて出しているので、
-- 「3章の時点では、誰と誰が知り合いだったか」が分からない。
--
-- ------------------------------------------------------------
-- なぜ人物の側に持たせるか
--
-- 関係の側にも「変化の記録」はある。
-- ただ、その時点は「第5話」「再会のあと」のような
-- 自由に書ける文字で、何章と数えられない。
--
-- 人物に「1,2,5」と数字で持たせるほうが軽い。
-- 書くときに数字を入れるだけで済む。
--
-- ------------------------------------------------------------
-- 決めていない人は、これまでどおり
--
-- 空のままなら「全部の章に出る」として扱う。
-- 既にある作品は、何もしなくても今までと同じに見える。
-- 入れた人だけが、章で絞れるようになる。
-- ============================================================

alter table public.resource_entries
    add column if not exists chapters smallint[];

comment on column public.resource_entries.chapters is
    '登場する章。空なら全部の章に出るものとして扱う';

notify pgrst, 'reload schema';

-- ============================================================
-- 確認
-- ============================================================
select
    case
        when exists (
            select 1 from information_schema.columns
            where table_schema = 'public'
              and table_name = 'resource_entries'
              and column_name = 'chapters'
        ) then '用意できました'
        else '失敗 ← 確認してください'
    end as 状態;

-- ============================================================
-- 原石航路 Studio
-- 受賞の見せ場：頁の切れ目を手で決める
--
-- ------------------------------------------------------------
-- 何のために足すか
--
-- 「一度に何冊」という数だけで割ると、
-- 3・3・1 のように、最後だけ寂しい板ができる。
--
-- 大賞を 1 冊で見せたい、佳作は 3 冊まとめたい、
-- という並べ方は、数では表せない。
--
-- そこで、作品と作品のあいだに切れ目を置けるようにする。
-- 切れ目のところで板が変わる。
--
-- ------------------------------------------------------------
-- 092 で作った per_view について
--
-- もう読んでいない。列は残してあるが、害はない。
-- 冊数は運営が切れ目で決めるようになった。
-- 上限の 5 冊だけは、画面の側で押さえている。
-- ============================================================

alter table public.featured_novels
    add column if not exists starts_page boolean not null default false;

comment on column public.featured_novels.starts_page is
    'この作品から新しい板を始める。切れ目の印';

/*
 * ★ コンテストが変わるところは、これが false でも必ず切れる。
 *   別の催しの本が同じ板に並ぶと、
 *   横に立つ額の絵と、その本が結び付かないため。
 *
 * ★ 1 枚に 6 冊以上は入らない。板からはみ出す。
 *   切れ目を置かなくても、5 冊で切れる。
 */

notify pgrst, 'reload schema';

-- ============================================================
-- 確認
-- ============================================================
select
    case
        when exists (
            select 1 from information_schema.columns
            where table_schema = 'public'
              and table_name = 'featured_novels'
              and column_name = 'starts_page'
        ) then '用意できました'
        else '失敗 ← 確認してください'
    end as 状態;

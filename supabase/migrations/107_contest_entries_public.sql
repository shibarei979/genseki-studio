-- ============================================================
-- 原石航路 Studio
-- コンテストの応募作を、誰でも見られるようにする
--
-- ------------------------------------------------------------
-- いままで
--
-- 応募は、出した本人と運営しか読めなかった。
-- 「コンテストエントリー作品は見れないのでしょうか？」
-- という問い合わせが届いた。
--
-- ------------------------------------------------------------
-- なぜ見せるか
--
-- コンテストは、読んでもらう場でもある。
-- 応募作が誰にも読まれないまま締切を迎えるのは、
-- 出した人にとっても、場としても損。
--
-- ------------------------------------------------------------
-- 気を付けること
--
-- ★ 選考の印は見せない。
--
--   is_shortlisted（一次通過）や note（運営の覚え書き）が
--   応募中に見えると、選考そのものが成り立たない。
--
--   決まりでは列を分けられないので、
--   画面の側で読む列を絞る。
--   ここで許すのは「読めること」だけ。
--
-- ★ 下書きに戻された作品は、画面の側で外す。
--   応募したあとに非公開にした作品を開くと、
--   「見つかりません」に当たる。
-- ============================================================

drop policy if exists contest_entries_public_read on public.contest_entries;

create policy contest_entries_public_read
    on public.contest_entries for select
    to anon, authenticated
    using (true);

comment on table public.contest_entries is
    'コンテストの応募。誰でも読める。選考の印は画面の側で外す';

notify pgrst, 'reload schema';

-- ============================================================
-- 確認
-- ============================================================
select policyname as 決まり, cmd as 対象, qual as 条件
from pg_policies
where schemaname = 'public' and tablename = 'contest_entries'
order by cmd, policyname;

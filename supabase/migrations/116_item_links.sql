-- ============================================================
-- 原石航路 Studio
-- アイテムツリーの繋がりを決める
--
-- ------------------------------------------------------------
-- どう繋ぐか
--
-- ★ 段の中は、左から右へ。
--
--     ①→②→③→④
--
-- ★ 段の頭は、前の段の頭から。
--
--     Lv.1 ①
--          ↓
--     Lv.2 ①→②→③→④→⑤
--
--   こうすると、左の列が幹になり、
--   右へ枝が伸びる形になる。
--
-- ★ 絵と同じように、木に見える。
--
--   並んでいるだけでは、集める道筋が分からない。
--   線があると、どこから手を付けるかが決まる。
--
-- ------------------------------------------------------------
-- あとから変えられる
--
-- 運営の画面（無料ポイント → 品物と、繋がり）で
-- 1 本ずつ選び直せる。
-- ここで決めるのは、初めの形。
-- ============================================================

-- ------------------------------------------------------------
-- ① 段の中を、左から右へ繋ぐ
-- ------------------------------------------------------------

update public.shop_items as later
set requires_item_id = earlier.id
from public.shop_items as earlier
where later.tier = earlier.tier
  and later.position = earlier.position + 1;

-- ------------------------------------------------------------
-- ② 段の頭を、前の段の頭に繋ぐ
-- ------------------------------------------------------------

update public.shop_items as head
set requires_item_id = above.id
from public.shop_items as above
where head.position = 0
  and above.tier = head.tier - 1
  and above.position = 0;

-- ------------------------------------------------------------
-- ③ いちばん初めの品物は、前提なし
-- ------------------------------------------------------------

update public.shop_items
set requires_item_id = null
where tier = 1 and position = 0;

-- ============================================================
-- 確認
-- ============================================================
select
    n.tier                                   as 段,
    n.position                               as 並び,
    n.name                                   as 名前,
    coalesce(
        'Lv' || p.tier || '-' || p.position,
        '（はじまり）'
    )                                        as 前の品物
from public.shop_items n
left join public.shop_items p on p.id = n.requires_item_id
order by n.tier, n.position;

-- ============================================================
-- 原石航路 Studio
-- 題名の空いている話に、番号を入れる
--
-- 話の見出しから「第◯話」を外し、題名をそのまま出すようにした。
-- そのままだと、題名の無い話が空欄で並んでしまう。
--
-- いまある分だけ、題名に「◯話」を入れておく。
-- 気に入らなければ、書き手が自分で直せる。
--
-- 何度実行しても壊れない（空のものだけ埋める）。
-- ============================================================

update public.episodes
   set title = ep_number || '話'
 where title is null
    or btrim(title) = '';

-- ============================================================
-- 確認
-- ============================================================
select
    case
        when count(*) = 0 then '空の題名はありません'
        else count(*)::text || '件、まだ空です ← 見せてください'
    end as 状態
from public.episodes
where title is null or btrim(title) = '';

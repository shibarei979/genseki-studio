-- ============================================================
-- 原石航路 Studio
-- 関係の線に、中間点を持たせる
--
-- ------------------------------------------------------------
-- 何のために足すか
--
-- いまの線は、中心へ少し引き寄せて曲げている。
-- 決まった曲げ方なので、線が重なったり、
-- 人の名前を横切ったりすることがある。
--
-- 中間点をつまんで動かせるようにする。
-- 作者が、線の通り道を決められる。
--
-- ------------------------------------------------------------
-- 決めていない線は、これまでどおり
--
-- null なら、今までの曲げ方をする。
-- 何もしなくても、見た目は変わらない。
-- ============================================================

alter table public.resource_relations
    add column if not exists bend jsonb;

comment on column public.resource_relations.bend is
    '線の中間点 {x, y}。null なら中心へ引き寄せる既定の曲げ方';

notify pgrst, 'reload schema';

-- ============================================================
-- 確認
-- ============================================================
select
    case
        when exists (
            select 1 from information_schema.columns
            where table_schema = 'public'
              and table_name = 'resource_relations'
              and column_name = 'bend'
        ) then '用意できました'
        else '失敗 ← 確認してください'
    end as 状態;

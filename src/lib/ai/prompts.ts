export const EXTRACT_SYSTEM_PROMPT = `あなたは小説の執筆支援ツールの一部です。
渡された本文を読み、作品資料に登録すべき要素を「もれなく」抜き出します。

【最も大事なこと】
名前を拾うだけでは資料になりません。
本文の書きぶりから読み取れることを、すべて添えてください。

たとえば「リオは弟の手を引いて走った」という一文からは、
　・リオという人物がいる
　・リオには弟がいる（弟も人物として登録する）
　・リオは弟を庇う立場にある
の 3 つが読み取れます。名前だけを返すのは誤りです。

直接書かれていなくても、書きぶりから確実に言えることは拾います。
敬語で話しかけられていれば目上、制服の描写があれば学生、
「また来たのか」と言われていれば再訪です。
ただし、本文から言えないことを作ってはいけません。
髪の色が書かれていないのに髪の色を決めるのは誤りです。

【必ず拾うもの】
- 固有名詞のすべて（人名・地名・組織名・作品独自の用語）
- 敬称や愛称がついた呼びかけ（「父さん」「先生」など）
- 建物・部屋・道・自然物など、場面の舞台になっている場所
  （「石段」「森」のような一般名詞でも、その場面の舞台なら拾う）
- 道具・持ち物・衣服など、名前や特徴が書かれているもの
- 作品世界の決まりごと、能力、現象、制度、儀式、単位、暦
- 動物・乗り物・食べ物など、名前が与えられているもの
- 出来事（誰が何をしたか。場面の区切りになる動き）

  出来事は、あとで年表として読み返すためのものです。
  名前だけ並んでも、何があったのかが分からなければ意味がありません。

  ・name は、その場面に固有の題にする
    良い例「城門でリオが門番に止められる」「セラが手紙を燃やす」
    悪い例「出会い」「戦闘」「移動」「会話」
    同じ名前の出来事を二つ以上作ってはいけません。
    似た場面が続くなら、誰が・どこで・何をしたかで区別します。

  ・summary には、何が起きたかを本文に沿って書く
    誰が、何をして、どうなったか。空にしてはいけません。

  ・attributes には分かる範囲で
    「関わった人物」「場所」「きっかけ」「結果」など

【拾わないもの】
- 「彼」「それ」などの指示語
- 「今日」「少し」などの一般的な語で、その場かぎりのもの
- すでに登録済みとして渡された名前

【出力】
次の形の JSON だけを返します。前置きもコードブロックの記号も付けません。

{"candidates":[
  {
    "name": "名前",
    "kind": "character|place|organization|term|item|event",
    "summary": "40文字以内の説明",
    "context": "根拠となった本文の一文",
    "source": "第3話 12行目",
    "attributes": {
      "読み": "…", "役割": "…", "人物像": "…",
      "所在": "…", "見た目": "…", "由来": "…"
    },
    "relations": [
      { "to": "相手の名前", "label": "弟" }
    ],
    "confidence": 0.0〜1.0
  }
]}

本文は「=== 第N話 ===」で話ごとに区切られ、各行の先頭に「行番号|」が付いています。
source には、根拠となった一文がある場所を「第3話 12行目」の形で書きます。
行番号は行頭の数字をそのまま使ってください。

attributes は、その要素について本文から読み取れたことを
項目名と値の組で並べます。項目名は日本語で、内容に合うものを自由に。
人物なら 読み・役割・人物像・年齢・所属・見た目・口調 など。
場所なら 所在・様子・規模 など。
用語なら 意味・使われ方 など。
本文から読み取れない項目は入れません。空欄を並べるくらいなら省きます。

relations は、その要素と関わりのある別の要素があれば書きます。
label には「弟」「師匠」「所属先」のような、本文から言える関係だけを。
呼びかけ方・敬語の有無・立ち回りから読み取れる上下関係も含めてよい。
ただし推測で「恋人」などと決めてはいけません。

relations は必ず埋めてください。
人物が 2 人以上出てくる場面では、その 2 人の関わりが必ずあります。
「同行者」「話し相手」のような、ゆるい関わりでも構いません。

すでに資料にある名前（既知の名前）とも結んでください。
今回は拾わない人物でも、名前が分かっていれば to に書けます。

【量の目安】
- 20〜40 件を目安に、拾えるだけ拾う
- 1 つの要素につき attributes は 2〜5 項目を目安に
- 出来事は、本文にある場面の数だけ必ず入れる
- 出来事の name が重複していないか、返す前に必ず見直す`;

export function buildExtractUserPrompt(
    text: string,
    knownNames: string[],
    targets: string[],
): string {
    return [
        `抜き出す対象: ${targets.join("、")}`,
        /*
         * すでにある名前。
         *
         * 新しい項目としては返さないが、
         * relations の to には書いてよいと伝える。
         * ここを「含めない」とだけ言うと、関係まで落ちる。
         */
        knownNames.length > 0
            ? [
                  `登録済みの名前: ${knownNames.slice(0, 300).join("、")}`,
                  "これらは新しい項目としては返さないでください。",
                  "ただし relations の to には書いて構いません。",
              ].join("\n")
            : "登録済みの名前: なし",
        "",
        "本文に出てくる要素を、もれなく拾ってください。",
        "名前だけでなく、その要素について書きぶりから読み取れることを",
        "attributes に添えてください。名前だけ返すのは誤りです。",
        "",
        "--- 本文ここから ---",
        text,
        "--- 本文ここまで ---",
    ].join("\n");
}

/**
 * 図案づくりの指示。
 *
 * 画像の模型には system の枠が無いので、頼み文にすべて書く。
 * 「資料の目印」であることを外さないよう、
 * 作風の指定と禁止事項を毎回添える。
 */
import { findRealPlaces, MAP_ERA_PROMPT } from "@/lib/ai/real-places";
import type { MapEra } from "@/lib/ai/real-places";

const IMAGE_STYLE_TEXT: Record<string, string> = {
    crest: "組織や国家を表す紋章。盾の形を基本にした、旗印のような意匠",
    portrait: "人物を表す肖像。上半身のシルエットと配色で示し、顔立ちは描き込まない",
    scene: "場所を表す風景。遠景で、地形と空の重なりで示す",
    icon: "用語や道具を表す記号。図形の組み合わせで示す",
    map: [
        "上から見た地図。羊皮紙に描いた古地図のような趣き。",
        "海・陸・山・森・川・道・町を描き分け、町や地形の位置関係が分かるようにする。",
        "方位記号（コンパスローズ）を隅に入れる。",
        "地名は書かない（あとから書き手が印を置くため）。",
    ].join(" "),
};

const IMAGE_COMMON = [
    "淡い水彩画のような、落ち着いた色づかい。",
    "背景は白または淡い単色。余白を広く取る。",
    "文字・数字・記号は一切描かない。",
    "実在の人物や既存の作品を思わせる要素は入れない。",
].join(" ");

/**
 * 地図向けの指示。
 * 文字を禁じるのは同じだが、余白は取らない。
 * 地図は隅まで描かれていないと地図に見えない。
 */
const IMAGE_MAP_COMMON = [
    "淡い水彩と細いペン線。羊皮紙のような生成りの地色。",
    "画面の隅まで地形を描き、余白は作らない。",
    "文字・数字・地名は一切描かない。",
    "実在の国や地域をそのまま写さない。",
].join(" ");

/**
 * 図案の縦横。
 * 地図だけ横長にする。正方形の地図は、実際の地形として見えにくい。
 */
export function imageSizeFor(style: string): string {
    return style === "map" ? "1536x1024" : "1024x1024";
}

export function buildImageUserPrompt(
    name: string,
    style: string,
    hint?: string,
    era?: MapEra,
): string {
    const styleText = IMAGE_STYLE_TEXT[style] ?? IMAGE_STYLE_TEXT.icon;

    if (style !== "map") {
        return [
            "小説の資料に添える図案を描いてください。",
            `題材: ${name}`,
            hint
                ? [
                      "次の指定に厳密に従ってください。",
                      "書かれている特徴はすべて反映し、勝手に足したり変えたりしないこと。",
                      hint,
                  ].join("\n")
                : "",
            `構図: ${styleText}`,
            IMAGE_COMMON,
        ]
            .filter(Boolean)
            .join("\n");
    }

    /*
     * 地図は、実在の地名が出てきたら実際の地形に沿わせる。
     * 「東京湾」と書かれているのに架空の海岸線を描かれると、
     * 資料として使えない。読み手も作者も実際の形を知っている。
     */
    const realPlaces = findRealPlaces(name, hint);
    const eraText = era && era !== "unset" ? MAP_ERA_PROMPT[era] : "";

    return [
        "小説の舞台となる地図を描いてください。",
        `題材: ${name}`,
        hint
            ? [
                  "次の指定に厳密に従ってください。",
                  "書かれている地形と配置はすべて反映すること。",
                  hint,
              ].join("\n")
            : "",
        eraText ? `時代: ${eraText}` : "",
        realPlaces.length > 0
            ? [
                  `実在の地名が含まれます: ${realPlaces.join("、")}`,
                  "これらは実際の地形・海岸線・河川・位置関係に忠実に描いてください。",
                  "方角と縮尺の関係も、実際のものに合わせます。",
                  "架空の地形に置き換えないでください。",
              ].join("\n")
            : "",
        `構図: ${styleText}`,
        IMAGE_MAP_COMMON,
    ]
        .filter(Boolean)
        .join("\n");
}

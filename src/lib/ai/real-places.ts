/**
 * 文中の実在の地名を拾う。
 * 長いものから照合する。「東京湾」を「東京」で切らないため。
 */
export function findRealPlaces(...texts: (string | undefined)[]): string[] {
    const joined = texts.filter(Boolean).join(" ");
    if (!joined) return [];

    const sorted = [...ALL].sort((a, b) => b.length - a.length);
    const found: string[] = [];

    for (const place of sorted) {
        if (!joined.includes(place)) continue;
        // すでに拾った長い名前の一部なら数えない
        if (found.some((row) => row.includes(place))) continue;
        found.push(place);
    }

    return found.slice(0, 6);
}


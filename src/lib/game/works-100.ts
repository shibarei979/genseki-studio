/*
 * 芯 — 何の話か。
 *
 * ★ 暗い方向に寄せない。
 *
 *   前は 復讐・喪失・対立・謎 と、半分が暗かった。
 *   あらすじも「いなくなる」「消える」「忘れる」が並び、
 *   何を引いても重い話になっていた。
 *
 *   読む人が明るい気持ちで受け取れるものを増やす。
 *   暗いものを全部消しはしない。
 *   喪失は物語の芯として強く、書きたい人がいる。
 */
export const CORES = [
    "冒険",
    "恋",
    "笑い",
    "友情",
    "再起",
    "成長",
    "日常",
    "発見",
    "夢",
    "喪失",
] as const;

export type Place = (typeof PLACES)[number];
export type Core = (typeof CORES)[number];

export interface Work {
    title: string;
    /**
     * どういう話か。2 行。
     *
     * ★ あらすじとして書く。作り手のメモにしない。
     *
     *   「日常のすぐ隣にある断層を書く」では、
     *   何の話なのか誰にも分からない。
     *
     *   実際の投稿作品のあらすじは、こう組まれている。
     *
     *     ① 誰が、どういう状況にいるか
     *     ② 何が起きたか（きっかけ）
     *     ③ そこから何を追うことになるか
     *
     * ★ 1 行目で ①② を、2 行目で ③ を書く。
     *   固有の数字と物を入れる。
     *   「十七円」「三度目の冬」のような具体が、絵にする。
     */
    note: string[];
}

const w = (title: string, a: string, b: string): Work => ({
    title,
    note: [a, b],
});


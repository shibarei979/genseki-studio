/* ============================================================
 * 石
 *
 * ★ 名前は漢字二字でそろえる。
 *   並べたときに粒が揃い、石らしく見える。
 *   「私の原石は余韻」と言えることが、いちばん大事。
 *
 * ★ 褒めるが、安くしない。
 *   「すごい」ではなく「持っている人は多くない」。
 *   事実として言えることだけ書く。
 * ============================================================
 */

